    extension(char character)
    {
        public IEnumerable<(int Column, int Row)> ToGlyphCells() =>
            Patterns.TryGetValue(character, out var rows)
                ? rows.SelectMany((line, row) => line
                    .Select((cell, column) => (Cell: cell, Column: column))
                    .Where(item => item.Cell == '#')
                    .Select(item => (item.Column, row)))
                : [];
    }
